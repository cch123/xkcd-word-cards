function parseArgs(argv) {
  const parsed = {
    input: null,
    out: null,
    start: 1,
    limit: null,
    includeExisting: false,
    shardSize: 500,
    size: "1024x1536",
    quality: "medium"
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--input") {
      parsed.input = requireValue(argv, ++index, arg);
    } else if (arg === "--out") {
      parsed.out = requireValue(argv, ++index, arg);
    } else if (arg === "--start") {
      parsed.start = parsePositiveInt(requireValue(argv, ++index, arg), arg);
    } else if (arg === "--limit") {
      parsed.limit = parsePositiveInt(requireValue(argv, ++index, arg), arg);
    } else if (arg === "--include-existing") {
      parsed.includeExisting = true;
    } else if (arg === "--shard-size") {
      parsed.shardSize = parsePositiveInt(requireValue(argv, ++index, arg), arg);
      if (parsed.shardSize > 500) {
        throw new Error("--shard-size must be <= 500 because the bundled image CLI caps batches at 500 jobs");
      }
    } else if (arg === "--size") {
      parsed.size = requireValue(argv, ++index, arg);
    } else if (arg === "--quality") {
      parsed.quality = requireValue(argv, ++index, arg);
    } else if (arg === "--help" || arg === "-h") {
      console.log(`Usage:
  node scripts/build-gpt-image-card-batch.mjs [--input llm_enrichment.jsonl] [--out word-cards/gpt-image-style] [--start 1] [--limit 100] [--quality medium] [--shard-size 500]`);
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return parsed;
}

function parseJsonl(text) {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line, index) => {
      try {
        return JSON.parse(line);
      } catch (error) {
        throw new Error(`Invalid JSONL at line ${index + 1}: ${error.message}`);
      }
    });
}

function compactList(value, max) {
  return (Array.isArray(value) ? value : [])
    .filter(Boolean)
    .map((item) => compactSentence(String(item), 70))
    .slice(0, max);
}

function compactRoot(value) {
  return String(value)
    .replace(/[：:]/, " = ")
    .replace(/（[^）]*(?:词源|线索|助记|后缀|前缀)[^）]*）/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function compactSentence(value, max = 125) {
  const normalized = String(value || "-").replace(/\s+/g, " ").trim();
  if (normalized.length <= max) return normalized;
  return `${normalized.slice(0, Math.max(1, max - 3)).trimEnd()}...`;
}

function formatPos(pos) {
  const map = {
    noun: "n.",
    verb: "v.",
    adj: "adj.",
    adv: "adv.",
    phrase: "phrase",
    multiple: "multi.",
    conjunction: "conj.",
    "noun|verb": "n. / v."
  };
  return map[pos] || String(pos || "word");
}

function slug(value) {
  const slugged = String(value || "word")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
  return slugged || "word";
}

function chunk(items, size) {
  const chunks = [];
  for (let index = 0; index < items.length; index += size) {
    chunks.push(items.slice(index, index + size));
  }
  return chunks;
}

async function fileExists(file) {
  try {
    await stat(file);
    return true;
  } catch (error) {
    if (error && error.code === "ENOENT") return false;
    throw error;
  }
}

function parsePositiveInt(value, flag) {
  const parsed = Number.parseInt(value, 10);
  if (!Number.isInteger(parsed) || parsed < 1) {
    throw new Error(`${flag} must be a positive integer`);
  }
  return parsed;
}

function requireValue(argv, index, flag) {
  const value = argv[index];
  if (!value || value.startsWith("--")) {
    throw new Error(`${flag} requires a value`);
  }
  return value;
}
