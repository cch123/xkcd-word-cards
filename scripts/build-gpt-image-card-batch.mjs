import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

const options = parseArgs(process.argv.slice(2));
const inputPath = path.resolve(options.input ?? path.join(rootDir, "llm_enrichment.jsonl"));
const outRoot = path.resolve(options.out ?? path.join(rootDir, "word-cards", "gpt-image-style"));
const cardsDir = path.join(outRoot, "cards");
const jobsDir = path.join(outRoot, "jobs");
const promptsArchiveDir = path.join(outRoot, "prompts");
const docsDir = path.join(outRoot, "docs");

const allEntries = parseJsonl(await readFile(inputPath, "utf8"));
const startIndex = Math.max(0, options.start - 1);
const endIndex = options.limit ? Math.min(allEntries.length, startIndex + options.limit) : allEntries.length;
const selected = allEntries.slice(startIndex, endIndex);

await mkdir(cardsDir, { recursive: true });
await mkdir(jobsDir, { recursive: true });
await mkdir(promptsArchiveDir, { recursive: true });
await mkdir(docsDir, { recursive: true });

const jobs = [];
const manifestCards = [];

for (const [offset, entry] of selected.entries()) {
  const sourceIndex = startIndex + offset + 1;
  const filename = `${String(sourceIndex).padStart(4, "0")}-${slug(entry.word)}.png`;
  const outputPath = path.join(cardsDir, filename);
  const exists = await fileExists(outputPath);
  const card = {
    index: sourceIndex,
    word: entry.word,
    pos: entry.pos,
    cefr: entry.cefr,
    domain: entry.domain,
    topic_major: entry.topic_major,
    topic_minor: entry.topic_minor,
    file: path.posix.join("cards", filename),
    status: exists ? "exists" : "pending"
  };
  manifestCards.push(card);
  if (!exists || options.includeExisting) {
    jobs.push({
      model: "gpt-image-2",
      size: options.size,
      quality: options.quality,
      output_format: "png",
      moderation: "auto",
      out: filename,
      prompt: buildPrompt(entry)
    });
  }
}

const shards = chunk(jobs, options.shardSize);
const shardInfos = [];
for (const [index, shard] of shards.entries()) {
  const shardName = `prompts-${String(index + 1).padStart(2, "0")}.jsonl`;
  const shardPath = path.join(jobsDir, shardName);
  const shardText = `${shard.map((job) => JSON.stringify(job)).join("\n")}\n`;
  await writeFile(shardPath, shardText, "utf8");
  await writeFile(path.join(promptsArchiveDir, shardName), shardText, "utf8");
  shardInfos.push({
    index: index + 1,
    count: shard.length,
    file: path.posix.join("jobs", shardName)
  });
}

const manifest = {
  source: path.relative(rootDir, inputPath),
  sourceCount: allEntries.length,
  selectedStart: startIndex + 1,
  selectedCount: selected.length,
  pendingJobCount: jobs.length,
  existingCount: manifestCards.filter((card) => card.status === "exists").length,
  model: "gpt-image-2",
  size: options.size,
  quality: options.quality,
  outputFormat: "png",
  shardSize: options.shardSize,
  shards: shardInfos,
  cards: manifestCards
};

await writeFile(path.join(outRoot, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
await writeFile(path.join(docsDir, "generation-notes.md"), renderReadme(manifest), "utf8");

console.log(`Source entries: ${allEntries.length}`);
console.log(`Selected entries: ${selected.length}`);
console.log(`Existing images skipped: ${manifest.existingCount}`);
console.log(`Pending image jobs: ${jobs.length}`);
console.log(`Prompt shards: ${shards.length}`);
console.log(`Output: ${path.relative(rootDir, outRoot) || "."}`);

function buildPrompt(entry) {
  const meanings = compactList(entry.zh_meanings, 3).join("；") || "词义见例句";
  const synonyms = compactList(entry.synonyms, 4).join(", ") || "-";
  const antonyms = compactList(entry.antonyms, 4).join(", ") || "-";
  const roots = compactList(entry.roots_affixes, 3).map(compactRoot).join(" | ") || "no clear modern split";
  const phrases = compactList(entry.spoken_phrases, 3).join(" | ") || "-";
  const examples = Array.isArray(entry.examples) ? entry.examples.slice(0, 2) : [];
  const example1 = examples[0] ?? {};
  const example2 = examples[1] ?? {};
  const pos = formatPos(entry.pos);
  const cefr = entry.cefr || "";
  const header = `${pos}${cefr ? ` ${cefr}` : ""}`.trim();
  const usage = entry.usage_note || "";
  const comicHint = buildComicHint(entry, meanings, example1, example2);

  // The content is deliberately repeated in a compact "exact text" block. GPT Image
  // can still make OCR-like mistakes, but this format produced the approved preview
  // style and gives the model one canonical source of truth per card.
  return `Use case: stylized-concept
Asset type: English vocabulary card generated by image model
Reference style: A clean black-and-white xkcd-like hand-drawn vocabulary card like a careful notebook comic. Use thick rounded outer border, large hand-lettered title, simple stick-figure comic scenes, thin horizontal dividers, a fixed left icon column in the study rows, right-side mini doodles for every example row, and neat bilingual study notes. Create original artwork only. No logo, signature, watermark, existing characters, or copied panel.

Primary request: Generate one complete black-and-white hand-drawn vocabulary card for the JSONL word entry "${entry.word}".

Canvas and composition: Portrait card, 2:3 ratio. White paper background. Rounded rectangular outer border. Text should look handwritten but remain legible and neatly spaced. Follow this exact reference-card layout:
1. Top header panel: large word at top left, part of speech + CEFR under it, a pronunciation line under that, Chinese meanings under that, then a strong horizontal divider.
2. Middle teaching area: left large "comic clue" panel; right narrow "meaning" + "roots" panel. The comic clue panel may be split into two vignettes by a dashed vertical divider for multiple meanings.
3. Bottom study rows: full-width stacked rows separated by horizontal lines. Every row has a narrow left icon cell, then the field label and content.
4. Example rows are taller. Each example row must have the circled number icon on the left, exact English + exact Chinese sentence in the middle, and a separate boxed mini doodle on the right that illustrates that specific example. Do not omit these right-side example doodles.

Top header content:
"${entry.word}"
"${header}"
"pronunciation: /.../"
"${meanings}"
For the pronunciation line, replace /.../ with a common IPA pronunciation for "${entry.word}". Do not literally write "...".

Middle teaching area:
- Left panel title: "comic clue".
- Comic clue content: ${comicHint}
- If the word has multiple meanings, split the comic clue panel into two vignettes with a dashed vertical line, like the reference card.
- Right panel title 1: "meaning"; include "${meanings}".
- Right panel title 2: "roots"; include short bullet-style roots from the roots text below.
- Use simple stick figures and symbolic line art. Keep it educational and neutral. For slang, body, violence, legal, medical, or risky topics, avoid explicit anatomy, gore, sexual imagery, real weapons aimed at people, or distressing content; use safe symbolic doodles and text labels only.

Bottom rows, exact text to include without changing wording:
"synonyms: ${synonyms}"
"antonyms: ${antonyms}"
"roots: ${roots}"
"phrase: ${phrases}"
"example 1: ${compactSentence(example1.en)}"
"${compactSentence(example1.zh)}"
"example 2: ${compactSentence(example2.en)}"
"${compactSentence(example2.zh)}"
"usage: ${compactSentence(usage)}"

Mandatory icon and doodle requirements:
- Synonyms row: draw a star icon in the left icon cell.
- Antonyms row: draw an X/cross icon in the left icon cell.
- Roots row: draw a small sprout or potted plant icon in the left icon cell.
- Phrase row: draw a speech bubble icon in the left icon cell.
- Example 1 row: draw a circled "1" in the left icon cell AND draw a separate boxed mini doodle on the right side illustrating example 1.
- Example 2 row: draw a circled "2" in the left icon cell AND draw a separate boxed mini doodle on the right side illustrating example 2.
- Usage row: draw a lightbulb icon in the left icon cell.
- The two example mini doodles must be different from each other and directly match their example sentences. They are required, not optional.

Text fidelity constraints:
- Do not rewrite, simplify, replace, or invent the example sentences.
- Do not replace JSON examples with new examples.
- Keep the word spelling, CEFR, Chinese meanings, synonyms, antonyms, roots, phrase, examples, and usage from the text above.
- Include one pronunciation line in the top header. Use a common IPA pronunciation in slash marks. If unsure, use a conservative approximate IPA; do not omit the line.
- Do not add extra vocabulary facts beyond the requested card text.

Style constraints: black ink only, no color, no gray fill except very light paper texture, clean educational comic note style, simple stick figures, no photorealism, no brand names, no copyrighted characters, no watermark.`;
}

function buildComicHint(entry, meanings, example1, example2) {
  const word = entry.word;
  const examples = [example1.en, example2.en].filter(Boolean).join(" / ");
  const topic = [entry.domain, entry.topic_major, entry.topic_minor].filter(Boolean).join(", ");
  return `Draw a simple visual explanation of "${word}" meaning "${meanings}". Use one or two concrete clues from the examples if helpful: "${compactSentence(examples, 180)}". Topic context: ${topic}. Add only short labels that clarify the meaning.`;
}

